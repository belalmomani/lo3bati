#!/usr/bin/env python3
"""Regenerates template/behaviors/BuiltIns.java from the files in template/behaviors/lib/.

Run it after adding or removing a behavior in lib/ (idempotent):  python3 tools/gen_behavior_builtins.py
Every public class in lib/ that extends Behavior (and is not abstract) is listed, sorted by name.
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE = os.path.join(ROOT, "app/src/main/java/com/star4droid/template/behaviors")


def lib_classes():
    out = []
    lib = os.path.join(BASE, "lib")
    for f in sorted(os.listdir(lib)):
        if not f.endswith(".java"):
            continue
        src = open(os.path.join(lib, f), encoding="utf-8").read()
        name = f[:-5]
        if re.search(r"public\s+class\s+" + re.escape(name) + r"\s+extends\s+\w+", src) and "abstract class" not in src:
            out.append(name)
    return out


def main():
    names = lib_classes()
    lines = [
        "package com.star4droid.template.behaviors;",
        "",
        "import com.star4droid.template.behaviors.lib.*;",
        "",
        "/** GENERATED by tools/gen_behavior_builtins.py - do not edit; add a behavior as lib/<Name>.java and rerun the script. */",
        "public final class BuiltIns {",
        "\tprivate BuiltIns() {}",
        "",
        "\t/** All built-in behavior classes. */",
        "\tpublic static Class<?>[] all() {",
        "\t\treturn new Class<?>[] {",
    ]
    for i, n in enumerate(names):
        lines.append("\t\t\t%s.class%s" % (n, "," if i < len(names) - 1 else ""))
    lines += ["\t\t};", "\t}", "}", ""]
    path = os.path.join(BASE, "BuiltIns.java")
    new = "\n".join(lines)
    old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
    if old != new:
        open(path, "w", encoding="utf-8").write(new)
        print("BuiltIns.java updated: %d behaviors" % len(names))
    else:
        print("BuiltIns.java unchanged: %d behaviors" % len(names))


if __name__ == "__main__":
    sys.exit(main())
